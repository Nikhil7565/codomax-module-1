# Day 3 - Lists

fruits = ["Apple", "Banana", "Mango", "Orange"]

print("Fruits:", fruits)
print("First fruit:", fruits[0])
print("Number of fruits:", len(fruits))

# Add an item
fruits.append("Grapes")

print("After adding Grapes:", fruits)

print("\nAll fruits:")
for fruit in fruits:
    print(fruit)
